# Generates src/ReplicatedStorage/Shared/LangEn.lua from tools/lang/en.tsv
# Run tools/lang/extract.py to list fragments that still need a translation.
import os
here=os.path.dirname(os.path.abspath(__file__))
root=os.path.dirname(os.path.dirname(here))
def q(s): return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
rows=[]
for line in open(os.path.join(here,'en.tsv'),encoding='utf8'):
    line=line.rstrip('\n')
    if not line or line.startswith('#'): continue
    ru,en=line.split('\t',1)
    rows.append((ru,en))
out=['-- AUTO-GENERATED by tools/lang/gen.py from tools/lang/en.tsv. Do not edit by hand.','return {']
for ru,en in rows: out.append('\t['+q(ru)+'] = '+q(en)+',')
out.append('}')
open(os.path.join(root,'src/ReplicatedStorage/Shared/LangEn.lua'),'w',encoding='utf8').write('\n'.join(out)+'\n')
print(len(rows),'entries')
